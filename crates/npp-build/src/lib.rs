//! Build script helpers for Notepad++ plugins using the `npp` crate.
//!
//! [`generate_toolbar_icons`] checks SVG master icons against an [`IconStyle`], renders them for
//! the light and the dark theme into raw BGRA images and writes a Rust source file declaring one
//! `npp::ToolbarIcon` per SVG, ready to be `include!`d. [`minify_css`] shrinks style sheets
//! that a plugin embeds. [`link_resource_script`] links a version resource into the DLL.
//!
//! Master icon contract (enforced by [`validate_icon`]):
//! - `viewBox="0 0 N N"` with `N` = [`IconStyle::canvas_size`],
//! - the foreground is drawn with `currentColor`,
//! - other colors are the light theme values of [`IconStyle::accents`], written as `#RRGGBB`,
//! - stroke widths are taken from [`IconStyle::stroke_widths`],
//! - outline styles fill accents only ([`IconStyle::allows_foreground_fills`]),
//! - no gradients, patterns, images, text, filters, masks or partial opacity.

use std::fmt::Write as _;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

use resvg::{tiny_skia, usvg};

mod css;
pub mod icon_style;
mod resource;

pub use css::minify_css;
pub use icon_style::{IconStyle, ThemedColor};
pub use resource::{VERSION_HEADER, link_resource_script};

/// Covers the small (16 px) and the large (32 px) Notepad++ toolbar from 100 % to 200 % scaling.
pub const TOOLBAR_ICON_SIZES: [u32; 9] = [16, 20, 24, 28, 32, 40, 48, 56, 64];

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Theme {
	Light,
	Dark,
}

impl Theme {
	pub const ALL: [Theme; 2] = [Theme::Light, Theme::Dark];

	fn name(self) -> &'static str {
		match self {
			Theme::Light => "light",
			Theme::Dark => "dark",
		}
	}
}

/// Validates and renders every `*.svg` in `svg_directory` and writes `generated_rust_file`.
/// The image data is written next to it. Emits the `cargo:rerun-if-changed` lines.
/// Fails with all style violations of all icons at once.
pub fn generate_toolbar_icons(
	svg_directory: &Path,
	generated_rust_file: &Path,
	style: &IconStyle,
) -> io::Result<()> {
	println!("cargo:rerun-if-changed={}", svg_directory.display());
	let output_directory = generated_rust_file.parent().unwrap_or(Path::new("."));
	let svg_files = svg_files_in(svg_directory)?;

	let mut violations = Vec::new();
	let mut sources = Vec::new();
	for svg_file in &svg_files {
		println!("cargo:rerun-if-changed={}", svg_file.display());
		let svg_source = fs::read_to_string(svg_file)?;
		if let Err(icon_violations) = validate_icon(&svg_source, style) {
			violations.extend(
				icon_violations
					.into_iter()
					.map(|violation| format!("{}: {violation}", svg_file.display())),
			);
		}
		sources.push(svg_source);
	}
	if !violations.is_empty() {
		return Err(io::Error::other(format!(
			"toolbar icons violate the \"{}\" icon style:\n  {}",
			style.name,
			violations.join("\n  ")
		)));
	}

	let mut generated =
		String::from("// Generated by npp-build from SVG master icons. Do not edit.\n");
	for (svg_file, svg_source) in svg_files.iter().zip(&sources) {
		let stem = icon_name(svg_file)?;
		let mut initializers = [String::new(), String::new()];
		for (theme, initializer) in Theme::ALL.into_iter().zip(&mut initializers) {
			for size in TOOLBAR_ICON_SIZES {
				let image_path =
					output_directory.join(format!("{stem}.{}.{size}.bgra", theme.name()));
				fs::write(&image_path, render_icon(svg_source, style, theme, size)?)?;
				write!(
					initializer,
					"::npp::IconImage {{ size: {size}, bgra: include_bytes!({:?}) }}, ",
					image_path.display().to_string()
				)
				.expect("writing to a String cannot fail");
			}
		}
		let [light, dark] = initializers;
		writeln!(
			generated,
			"pub static {}: ::npp::ToolbarIcon = ::npp::ToolbarIcon {{\n\tlight: &[{light}],\n\tdark: &[{dark}],\n}};",
			constant_name(stem)
		)
		.expect("writing to a String cannot fail");
	}
	fs::write(generated_rust_file, generated)
}

/// `*.svg` files in `directory`, sorted by name.
pub fn svg_files_in(directory: &Path) -> io::Result<Vec<PathBuf>> {
	let mut svg_files: Vec<PathBuf> = fs::read_dir(directory)?
		.map(|entry| entry.map(|entry| entry.path()))
		.collect::<io::Result<_>>()?;
	svg_files.retain(|path| path.extension().is_some_and(|extension| extension == "svg"));
	svg_files.sort();
	Ok(svg_files)
}

/// Returns every rule violation, each as a human readable sentence.
pub fn validate_icon(svg_source: &str, style: &IconStyle) -> Result<(), Vec<String>> {
	let mut violations = Vec::new();
	if svg_source.contains("<text") {
		violations.push("text is not allowed, draw glyphs as paths".to_owned());
	}
	for theme in Theme::ALL {
		let tree = match parse_themed(svg_source, style, theme) {
			Ok(tree) => tree,
			Err(error) => {
				violations.push(format!("cannot be parsed: {error}"));
				return Err(violations);
			}
		};
		let size = tree.size();
		let canvas = style.canvas_size as f32;
		if theme == Theme::Light && (size.width() != canvas || size.height() != canvas) {
			violations.push(format!(
				"canvas is {}x{}, expected viewBox=\"0 0 {canvas} {canvas}\"",
				size.width(),
				size.height()
			));
		}
		let mut theme_violations = Vec::new();
		check_group(tree.root(), style, theme, &mut theme_violations);
		// Dark theme violations are mostly echoes of light theme ones, except for colors written in
		// a notation the recoloring does not recognize.
		if theme == Theme::Light || violations.is_empty() {
			violations.extend(theme_violations);
		}
	}
	let mut seen = std::collections::HashSet::new();
	violations.retain(|violation| seen.insert(violation.clone()));
	if violations.is_empty() { Ok(()) } else { Err(violations) }
}

/// Renders a master icon. Output format: see `npp::IconImage` (BGRA, straight alpha, top-down).
pub fn render_icon(
	svg_source: &str,
	style: &IconStyle,
	theme: Theme,
	size: u32,
) -> io::Result<Vec<u8>> {
	let pixmap = render_pixmap(svg_source, style, theme, size)?;
	Ok(pixmap
		.pixels()
		.iter()
		.flat_map(|pixel| {
			let color = pixel.demultiply();
			[color.blue(), color.green(), color.red(), color.alpha()]
		})
		.collect())
}

/// Renders a master icon into a premultiplied RGBA pixmap, e.g. for previews.
pub fn render_pixmap(
	svg_source: &str,
	style: &IconStyle,
	theme: Theme,
	size: u32,
) -> io::Result<tiny_skia::Pixmap> {
	let tree = parse_themed(svg_source, style, theme).map_err(io::Error::other)?;
	let mut pixmap =
		tiny_skia::Pixmap::new(size, size).ok_or_else(|| io::Error::other("invalid icon size"))?;
	let source_size = tree.size();
	let transform = tiny_skia::Transform::from_scale(
		size as f32 / source_size.width(),
		size as f32 / source_size.height(),
	);
	resvg::render(&tree, transform, &mut pixmap.as_mut());
	Ok(pixmap)
}

fn parse_themed(
	svg_source: &str,
	style: &IconStyle,
	theme: Theme,
) -> Result<usvg::Tree, usvg::Error> {
	let mut themed_source = svg_source.replace("currentColor", style.foreground.for_theme(theme));
	if theme == Theme::Dark {
		for accent in style.accents {
			themed_source = replace_ignoring_ascii_case(&themed_source, accent.light, accent.dark);
		}
	}
	usvg::Tree::from_str(&themed_source, &usvg::Options::default())
}

fn check_group(group: &usvg::Group, style: &IconStyle, theme: Theme, violations: &mut Vec<String>) {
	if group.opacity().get() < 1.0 {
		violations.push("partial opacity is not allowed".to_owned());
	}
	if !group.filters().is_empty() {
		violations.push("filters are not allowed".to_owned());
	}
	if group.mask().is_some() {
		violations.push("masks are not allowed".to_owned());
	}
	for node in group.children() {
		match node {
			usvg::Node::Group(child) => check_group(child, style, theme, violations),
			usvg::Node::Path(path) => check_path(path, style, theme, violations),
			usvg::Node::Image(_) => violations.push("embedded images are not allowed".to_owned()),
			usvg::Node::Text(_) => violations.push("text is not allowed".to_owned()),
		}
	}
}

fn check_path(path: &usvg::Path, style: &IconStyle, theme: Theme, violations: &mut Vec<String>) {
	if let Some(fill) = path.fill() {
		check_paint(fill.paint(), fill.opacity().get(), style, theme, violations);
		let foreground = icon_style::parse_hex_color(style.foreground.for_theme(theme));
		if !style.allows_foreground_fills
			&& matches!(fill.paint(), usvg::Paint::Color(color) if Some((color.red, color.green, color.blue)) == foreground)
		{
			violations.push(
				"the foreground is outline only (stroke it, add fill=\"none\"); fills are for accents"
					.to_owned(),
			);
		}
	}
	if let Some(stroke) = path.stroke() {
		check_paint(stroke.paint(), stroke.opacity().get(), style, theme, violations);
		let transform = path.abs_transform();
		let scale = (transform.sx * transform.sy - transform.kx * transform.ky).abs().sqrt();
		let width = stroke.width().get() * scale;
		if !style.stroke_widths.iter().any(|allowed| (allowed - width).abs() < 0.01) {
			violations
				.push(format!("stroke width {width} is not one of {:?}", style.stroke_widths));
		}
	}
}

fn check_paint(
	paint: &usvg::Paint,
	opacity: f32,
	style: &IconStyle,
	theme: Theme,
	violations: &mut Vec<String>,
) {
	if opacity < 1.0 {
		violations.push("partial fill or stroke opacity is not allowed".to_owned());
	}
	let usvg::Paint::Color(color) = paint else {
		violations.push("gradients and patterns are not allowed".to_owned());
		return;
	};
	let actual = (color.red, color.green, color.blue);
	if style
		.colors_for_theme(theme)
		.any(|allowed| icon_style::parse_hex_color(allowed) == Some(actual))
	{
		return;
	}
	let color = format!("#{:02X}{:02X}{:02X}", color.red, color.green, color.blue);
	violations.push(match theme {
		Theme::Light => {
			let accents: Vec<&str> = style.accents.iter().map(|accent| accent.light).collect();
			let hint = if color == "#000000" {
				"; SVG fills shapes black by default, add fill=\"none\""
			} else {
				""
			};
			format!(
				"color {color} is not part of the palette (use currentColor or one of {accents:?}){hint}"
			)
		}
		Theme::Dark => {
			format!("color {color} was not recolored for the dark theme (write it as #RRGGBB)")
		}
	});
}

fn replace_ignoring_ascii_case(text: &str, needle: &str, replacement: &str) -> String {
	let lowercase_text = text.to_ascii_lowercase();
	let lowercase_needle = needle.to_ascii_lowercase();
	let mut result = String::with_capacity(text.len());
	let mut copied_until = 0;
	// ASCII lowercasing keeps byte offsets, so matches in the lowercase copy map 1:1.
	for (start, _) in lowercase_text.match_indices(&lowercase_needle) {
		result.push_str(&text[copied_until..start]);
		result.push_str(replacement);
		copied_until = start + needle.len();
	}
	result.push_str(&text[copied_until..]);
	result
}

fn icon_name(svg_file: &Path) -> io::Result<&str> {
	svg_file
		.file_stem()
		.and_then(|stem| stem.to_str())
		.ok_or_else(|| io::Error::other(format!("non UTF-8 icon name: {}", svg_file.display())))
}

fn constant_name(stem: &str) -> String {
	stem.chars()
		.map(
			|character| {
				if character.is_ascii_alphanumeric() { character.to_ascii_uppercase() } else { '_' }
			},
		)
		.collect()
}

#[cfg(test)]
mod tests {
	use super::*;

	const TEST_STYLE: IconStyle = IconStyle {
		name: "test",
		canvas_size: 16,
		foreground: ThemedColor { role: "foreground", light: "#102030", dark: "#E0E0E0" },
		accents: &[ThemedColor { role: "accent", light: "#0078D4", dark: "#4CC2FF" }],
		stroke_widths: &[1.0],
		allows_foreground_fills: false,
	};

	fn svg(body: &str) -> String {
		format!(r#"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16">{body}</svg>"#)
	}

	#[test]
	fn renders_left_half_opaque_and_right_half_transparent() {
		let source = svg(r#"<rect width="8" height="16" fill="currentColor"/>"#);
		let pixels = render_icon(&source, &TEST_STYLE, Theme::Light, 16).unwrap();
		assert!(validate_icon(&source, &TEST_STYLE).unwrap_err()[0].contains("outline only"));
		assert_eq!(pixels.len(), 16 * 16 * 4);
		assert_eq!(&pixels[0..4], &[0x30, 0x20, 0x10, 0xFF]);
		assert_eq!(pixels[15 * 4 + 3], 0);
	}

	#[test]
	fn recolors_accents_for_dark_theme() {
		let source = svg(r##"<rect width="16" height="16" fill="#0078d4"/>"##);
		let pixels = render_icon(&source, &TEST_STYLE, Theme::Dark, 16).unwrap();
		assert_eq!(&pixels[0..4], &[0xFF, 0xC2, 0x4C, 0xFF]);
	}

	#[test]
	fn accepts_icons_following_the_style() {
		let source = svg(
			r##"<path d="M1.5 1.5h13" fill="none" stroke="currentColor"/><rect x="2" y="4" width="4" height="4" fill="#0078D4"/>"##,
		);
		assert_eq!(validate_icon(&source, &TEST_STYLE), Ok(()));
	}

	#[test]
	fn reports_style_violations() {
		let source = r##"<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24"><path d="M1 1h13" stroke="red" stroke-width="2"/><rect width="4" height="4" fill="currentColor" fill-opacity="0.5"/></svg>"##;
		let violations = validate_icon(source, &TEST_STYLE).unwrap_err();
		let report = violations.join("\n");
		assert!(report.contains("canvas is 24x24"), "{report}");
		assert!(report.contains("color #FF0000"), "{report}");
		assert!(report.contains("stroke width 2"), "{report}");
		assert!(report.contains("partial fill or stroke opacity"), "{report}");
	}

	#[test]
	fn rejects_colors_the_dark_recoloring_would_miss() {
		let source = svg(r#"<rect width="4" height="4" fill="rgb(0,120,212)"/>"#);
		let violations = validate_icon(&source, &TEST_STYLE).unwrap_err();
		assert!(violations.join("\n").contains("color #0078D4"), "{violations:?}");
	}

	#[test]
	fn derives_constant_names_from_file_names() {
		assert_eq!(constant_name("markdown-table"), "MARKDOWN_TABLE");
	}
}
