//! `update-emoji`: regenerates `crates/npp-toolbox/src/emoji_table.rs`, the GitHub emoji
//! shortcodes (`:smile:`), from GitHub's gemoji database.
//!
//! Only the shortcodes and their emoji are taken over. The download is cached in
//! `target/emoji/<revision>/`.

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use crate::json::{JsonValue, parse_json};
use crate::npp_interface::{download, run_rustfmt};

const RAW_FILES_URL: &str = "https://raw.githubusercontent.com/github/gemoji";
const DATABASE_PATH: &str = "db/emoji.json";
pub const GENERATED_FILE: &str = "crates/npp-toolbox/src/emoji_table.rs";

/// `revision`: a gemoji branch, tag or commit. `master` when `None`.
pub fn update(workspace_root: &Path, revision: Option<&str>) -> Result<(), String> {
	let revision = revision.unwrap_or("master");
	let cache_directory = workspace_root.join("target/emoji").join(revision);
	fs::create_dir_all(&cache_directory)
		.map_err(|error| format!("cannot create {}: {error}", cache_directory.display()))?;
	let database_file = cache_directory.join("emoji.json");
	if !database_file.exists() {
		download(&format!("{RAW_FILES_URL}/{revision}/{DATABASE_PATH}"), &database_file)?;
	}
	let database = fs::read_to_string(&database_file)
		.map_err(|error| format!("cannot read {}: {error}", database_file.display()))?;

	let shortcodes = shortcodes_of(&parse_json(&database)?)?;
	let generated = generate_table(&shortcodes, revision);
	let generated_file = workspace_root.join(GENERATED_FILE);
	fs::write(&generated_file, generated)
		.map_err(|error| format!("cannot write {}: {error}", generated_file.display()))?;
	run_rustfmt(&generated_file)?;
	println!("{GENERATED_FILE}: {} shortcodes from gemoji {revision}", shortcodes.len());
	Ok(())
}

/// `(shortcode, emoji)` sorted by shortcode bytes, as the binary search in the plugin expects.
fn shortcodes_of(database: &JsonValue) -> Result<Vec<(String, String)>, String> {
	let JsonValue::Array(entries) = database else {
		return Err(format!("{DATABASE_PATH}: expected an array of emoji"));
	};
	let mut shortcodes = Vec::new();
	for entry in entries {
		let (Some(JsonValue::String(emoji)), Some(JsonValue::Array(aliases))) =
			(entry.field("emoji"), entry.field("aliases"))
		else {
			return Err(format!("{DATABASE_PATH}: entry without \"emoji\" or \"aliases\""));
		};
		for alias in aliases {
			let JsonValue::String(alias) = alias else {
				return Err(format!("{DATABASE_PATH}: alias of {emoji} is not a string"));
			};
			if !alias.bytes().all(is_shortcode_byte) {
				return Err(format!("{DATABASE_PATH}: unexpected shortcode {alias:?}"));
			}
			shortcodes.push((alias.clone(), emoji.clone()));
		}
	}
	shortcodes.sort();
	shortcodes.dedup_by(|next, previous| next.0 == previous.0);
	Ok(shortcodes)
}

/// The characters the plugin accepts between the colons of a shortcode.
fn is_shortcode_byte(byte: u8) -> bool {
	byte.is_ascii_lowercase() || byte.is_ascii_digit() || b"_+-".contains(&byte)
}

fn generate_table(shortcodes: &[(String, String)], revision: &str) -> String {
	let mut source = format!(
		"//! GitHub emoji shortcodes, generated by `cargo xtask update-emoji` from gemoji ({revision}).\n\
		 //! Do not edit by hand.\n\
		 //!\n\
		 //! gemoji: <https://github.com/github/gemoji>, MIT License, Copyright (c) 2019 GitHub, Inc.\n\n\
		 /// One `shortcode\\temoji\\n` line per shortcode, sorted by shortcode bytes.\n\
		 pub const SHORTCODES: &str = concat!(\n"
	);
	for (shortcode, emoji) in shortcodes {
		let _ = writeln!(source, "\t\"{shortcode}\\t{}\\n\",", emoji.escape_default());
	}
	source.push_str(");\n");
	source
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn collects_sorted_aliases() {
		let database = parse_json(
			r#"[{"emoji": "😄", "aliases": ["smile"]}, {"emoji": "👍", "aliases": ["+1", "thumbsup"]}]"#,
		)
		.expect("valid JSON");
		let shortcodes = shortcodes_of(&database).expect("valid database");
		let names: Vec<&str> = shortcodes.iter().map(|(name, _)| name.as_str()).collect();
		assert_eq!(names, ["+1", "smile", "thumbsup"]);
		assert!(generate_table(&shortcodes, "master").contains("\"+1\\t\\u{1f44d}\\n\","));
	}

	#[test]
	fn rejects_unexpected_shortcodes() {
		let database = parse_json(r#"[{"emoji": "x", "aliases": ["Upper Case"]}]"#).expect("JSON");
		assert!(shortcodes_of(&database).is_err());
	}
}
